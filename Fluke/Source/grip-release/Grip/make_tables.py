"""Generate the fixed-point tables for the OP-1's 44.1 kHz audio path."""
from math import exp, log10
from pathlib import Path

attack = (1, 2, 3, 5, 8, 12, 18, 25, 35, 50)
release = (20, 35, 50, 75, 100, 150, 220, 330, 500, 750)

def coefficient(ms):
    return round(32768 * (1 - exp(-1000 / (44100 * ms))))

def table(name, values):
    values = tuple(values)
    rows = ["    " + ", ".join(map(str, values[i:i+12])) + ","
            for i in range(0, len(values), 12)]
    return f"static const unsigned short {name}[] = {{\n" + "\n".join(rows) + "\n};\n"

tables = [
    table("attack_ms", attack),
    table("release_ms", release),
    table("attack_coef", map(coefficient, attack)),
    table("release_coef", map(coefficient, release)),
    table("loss_db64", [4096] + [round(-1280 * log10(i / 256))
                                for i in range(1, 257)]),
    table("gain_q15", [round(32768 * 10 ** (-i / 160)) for i in range(257)]),
    table("makeup_q12", [round(4096 * 10 ** (i / 20)) for i in range(13)]),
]
Path(__file__).with_name("tables.h").write_text(
    "/* Generated by make_tables.py. */\n" + "\n".join(tables))
