import math
from pathlib import Path
p=Path(__file__).parent/'tables.h'
tables={
 'BB_TIME': [round(44100*.03*(1/.03)**(i/127)) for i in range(128)],
 'BB_PITCH': [round(4096*2**(i/12)) for i in range(-72,80)],
 'BB_CUTOFF': [round(100*190**(i/127)) for i in range(128)],
 'BB_FILTER': [round(16384*(1-math.exp(-2*math.pi*(100*190**(i/127))/44100))) for i in range(128)],
 'BB_ENV': [round(32767*(.5-.5*math.cos(math.pi*i/256))) for i in range(257)],
 'BB_ATAN': [round(16384*math.atan(i/32)) for i in range(257)]}
# Q14 Catmull-Rom weights. Integer positions stay exact; coefficient rows sum to unity.
cubic=[]
for i in range(512):
 f=i/512
 w=[-.5*f+f*f-.5*f*f*f,1-2.5*f*f+1.5*f*f*f,.5*f+2*f*f-1.5*f*f*f,-.5*f*f+.5*f*f*f]
 q=[round(x*16384) for x in w];q[1]+=16384-sum(q);cubic.extend(q)
tables['BB_CUBIC']=cubic
# Original +bubbler feedback biquad coefficients, Q28. Prepared on host,
# never tan/sqrt/division in the audio interrupt. Resonance zero keeps v0.3 DSP.
res=[]
for tone in range(128):
 f0=(100*190**(tone/127))/44100
 c=1/(f0*math.pi) if f0<.1 else math.tan((.5-f0)*math.pi)
 for r in range(64):
  damping=(1-r/63)*(math.sqrt(2)-.1)+.1
  a=1/(1+damping*c+c*c)
  res.extend(round(v*(1<<28)) for v in [a,2*(1-c*c)*a,(1-damping*c+c*c)*a])
tables['BB_RESONANT']=res
s='/* Generated by make_tables.py; no floating point runs on the OP-1. */\n'
for name,values in tables.items():
 typ='short' if name in ['BB_ENV','BB_ATAN','BB_CUBIC'] else 'int'
 s+=f'static const {typ} {name}[{len(values)}] = {{\n'
 for i in range(0,len(values),12):s+='    '+', '.join(map(str,values[i:i+12]))+',\n'
 s+='};\n'
p.write_text(s)
